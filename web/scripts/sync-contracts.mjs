// Copies compiled ABIs and deployment addresses from ../contracts into src/lib/generated.
// Run after `forge build` / a deployment: `npm run sync`.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contracts = join(root, "..", "contracts");
const outDir = join(root, "src", "lib", "generated");
mkdirSync(outDir, { recursive: true });

const names = ["KriyaExecutor", "KriyaVault", "KriyaMandate", "KriyaStrategyRegistry", "MockUSDC", "MockStrategy"];
let abis = "// AUTO-GENERATED by scripts/sync-contracts.mjs. Do not edit.\n\n";
for (const name of names) {
  const artifact = JSON.parse(readFileSync(join(contracts, "out", `${name}.sol`, `${name}.json`), "utf8"));
  abis += `export const ${name}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(outDir, "abis.ts"), abis);

const depDir = join(contracts, "deployments");
const deployments = {};
if (existsSync(depDir)) {
  for (const f of readdirSync(depDir).filter((f) => f.endsWith(".json"))) {
    const d = JSON.parse(readFileSync(join(depDir, f), "utf8"));
    deployments[d.chainId] = d;
  }
}
writeFileSync(
  join(outDir, "deployments.ts"),
  "// AUTO-GENERATED by scripts/sync-contracts.mjs. Do not edit.\n\n" +
    `export const deployments = ${JSON.stringify(deployments, null, 2)} as const;\n`,
);
console.log(`Synced ${names.length} ABIs and deployments for chains: ${Object.keys(deployments).join(", ") || "none"}`);
